    private void connetti() {
        new Thread(() -> {
            try {
                socket = new Socket(HOST, PORTA);
                out = new DataOutputStream(socket.getOutputStream());
                in = new DataInputStream(socket.getInputStream());

                SwingUtilities.invokeLater(() -> btnPersonalita.setEnabled(true));

                while (true) {
                    String msg = in.readUTF();
                    SwingUtilities.invokeLater(() -> riceviMessaggio(msg));
                }
            } catch (IOException e) {
                SwingUtilities.invokeLater(this::connessioneChiusa);
            }
        }).start();
    }

    private void manda(String comando) {
        try {
            out.writeUTF(comando);
        } catch (IOException e) {
            connessioneChiusa();
        }
    }
    
    private void connessioneChiusa() {
        txtAreaRisposta.append("Disconnesso dal server.\n");
        btnPersonalita.setEnabled(false);
        txtDomanda.setEnabled(false);
        btnInvio.setEnabled(false);
    }
    private void inviaDomanda() {
        String testo = txtDomanda.getText().trim();
        if (testo.isEmpty()) return;
        txtAreaRisposta.append("Tu: " + testo + "\n");
        manda("DOMANDA_" + testo);
        txtDomanda.setText("");
    }
    private void riceviMessaggio(String msg) {
        txtAreaRisposta.append("Oracolo: " + msg + "\n\n");
        txtAreaRisposta.setCaretPosition(txtAreaRisposta.getDocument().getLength());
        if (msg.startsWith("Personalità impostata")) {
        txtDomanda.setEnabled(true);
        btnInvio.setEnabled(true);
        txtDomanda.requestFocus();
        }
    }
